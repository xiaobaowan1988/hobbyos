/*
 * include/uart.h — PL011 UART 驱动头文件
 *
 * 声明 UART 初始化和读写函数, 供内核其他模块调用。
 *
 * 参考文档:
 *   [PL011-TRM] ARM PrimeCell UART (PL011) Technical Reference Manual (DDI 0183)
 */

#ifndef UART_H
#define UART_H

/* ==================================================================
 * uart_init() — 初始化 PL011 UART0
 *
 * 必须在调用任何其他 uart_* 函数之前调用。
 * 配置: 115200 bps, 8N1, FIFO 启用, 轮询模式。
 * ================================================================== */
void uart_init(void);

/* ==================================================================
 * uart_putc() — 发送单个字符 (阻塞式)
 *
 * 如果发送 FIFO 已满, 将忙等待直到有空间。
 * 参数: c — 要发送的字符
 * ================================================================== */
void uart_putc(char c);

/* ==================================================================
 * uart_puts() — 发送以 null 结尾的字符串
 *
 * 自动将 '\n' 转换为 '\r\n' (串口 CR/LF 惯例)。
 * 参数: s — 指向字符串的指针
 * ================================================================== */
void uart_puts(const char *s);

/* ==================================================================
 * uart_getc() — 接收单个字符 (阻塞式)
 *
 * 如果接收 FIFO 为空, 将忙等待直到有数据。
 * 返回: 接收到的字符
 * ================================================================== */
char uart_getc(void);

#endif /* UART_H */
